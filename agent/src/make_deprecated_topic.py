#!/usr/bin/env python3
"""Generate topics/deprecated-apis.md from corrections.yaml.

    python3 agent/src/make_deprecated_topic.py          rewrite the topic
    python3 agent/src/make_deprecated_topic.py --check  exit 1 if the topic is stale
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.dont_write_bytecode = True
sys.path.insert(0, str(HERE))
from check_swift import load_rules  # noqa: E402

TOPIC = HERE / "topics" / "deprecated-apis.md"

HEADER = """---
id: deprecated-apis
title: Deprecated and outdated SwiftUI APIs
platforms: [iOS, iPadOS, macOS]
generated-from: agent/src/corrections.yaml
reviewed: {reviewed}
---

# Deprecated and outdated SwiftUI APIs

<!-- Generated by agent/src/make_deprecated_topic.py from corrections.yaml. Edit that file, not this one. -->

Models trained on older code keep writing the left side. Write the right side when your deployment target is at least the version in parentheses; below it, keep the old form or gate the new one with `if #available`. Versions are iOS; the macOS floor matches (iOS 13–18 = macOS 10.15–15, and 26+ is the same number). No version means any OS. `check-swift.sh` flags every row.
"""

SECTIONS = [
    ("error", "Deprecated, and the compiler warns", "Fix these now."),
    ("warning", "Deprecated or superseded",
     "Many are deprecated only in Apple's docs so far, so nothing warns. Don't write them in new code. "
     "`ObservableObject` never warns, but `@Observable` views update only for properties they read; "
     "don't mix the two systems in one model."),
    ("info", "Judgment calls", "Usually wrong in new code, sometimes right. Decide case by case."),
]

FOOTER = """
## Apple docs

- https://developer.apple.com/documentation/swiftui/migrating-from-the-observable-object-protocol-to-the-observable-macro.md
- https://developer.apple.com/documentation/swiftui/migrating-to-new-navigation-types.md
- https://developer.apple.com/documentation/updates/swiftui.md
"""


def floor(min_os: str) -> str:
    """'iOS 17, macOS 14' -> ' (17)'; 'macOS 14' alone -> ' (macOS 14)'; 'any…' -> ''."""
    m = re.search(r"\biOS\s+(\d+(?:\.\d+)?)", min_os)
    if m:
        return f" ({m.group(1)})"
    m = re.search(r"\bmacOS\s+(\d+(?:\.\d+)?)", min_os)
    return f" (macOS {m.group(1)})" if m else ""


def render(entries: list[dict], reviewed: str) -> str:
    out = [HEADER.format(reviewed=reviewed)]
    for severity, title, note in SECTIONS:
        rows = [e for e in entries if e.get("severity", "warning") == severity]
        if not rows:
            continue
        out.append(f"## {title}\n")
        out.append(note + "\n")
        for e in rows:
            out.append(f"- {e['brief']}{floor(e['min_os'])}")
        out.append("")
    out.append(FOOTER)
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    entries = load_rules(HERE / "corrections.yaml")
    reviewed = "2026-10-26"
    if TOPIC.exists():
        for line in TOPIC.read_text(encoding="utf-8").splitlines():
            if line.startswith("reviewed:"):
                reviewed = line.split(":", 1)[1].strip()
    text = render(entries, reviewed)
    if "--check" in sys.argv:
        if not TOPIC.exists() or TOPIC.read_text(encoding="utf-8") != text:
            print(f"{TOPIC} is stale; run python3 agent/src/make_deprecated_topic.py")
            return 1
        print(f"{TOPIC.name} is up to date")
        return 0
    TOPIC.write_text(text, encoding="utf-8")
    print(f"wrote {TOPIC} ({len(text)} chars, {len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
