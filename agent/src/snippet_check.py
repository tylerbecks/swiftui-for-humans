#!/usr/bin/env python3
"""Extract the agent sources' Swift snippets into temporary files the app targets build.

Every example_new in corrections.yaml and every ```swift block in topics/*.md becomes
one file, so names never collide: top-level declarations are made fileprivate. Code
fences can carry flags after the language:

    ```swift            builds for iOS and macOS
    ```swift ios        iOS only
    ```swift macos      macOS only
    ```swift nocompile  never built (a deliberate "don't" sample or a fragment)

Usage (from anywhere):
    python3 agent/src/snippet_check.py write    # writes SwiftUIForHumans/{iOS,macOS}/_SnippetCheck/
    scripts/build.sh ios && scripts/build.sh mac
    python3 agent/src/snippet_check.py clean    # always delete them afterwards
"""

from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.dont_write_bytecode = True
sys.path.insert(0, str(HERE))
from check_swift import load_rules  # noqa: E402

OUT = {"ios": ROOT / "SwiftUIForHumans/iOS/_SnippetCheck", "macos": ROOT / "SwiftUIForHumans/macOS/_SnippetCheck"}
DECL = re.compile(r"^((?:@[\w.]+(?:\([^)\n]*\))?\s+)*)((?:final\s+)?(?:struct|class|enum|actor|protocol|func|let|var|extension|typealias)\b)", re.M)
FENCE = re.compile(r"^```swift([^\n]*)\n(.*?)^```", re.M | re.S)


def snippets():
    """Yield (name, platforms, code)."""
    for e in load_rules(HERE / "corrections.yaml"):
        plat = e.get("platforms", "all")
        yield f"corrections_{e['id']}", ({"ios", "macos"} if plat == "all" else {plat}), e["example_new"]
    for md in sorted((HERE / "topics").glob("*.md")):
        for n, m in enumerate(FENCE.finditer(md.read_text(encoding="utf-8")), start=1):
            flags = set(m.group(1).split())
            if "nocompile" in flags:
                continue
            plats = flags & {"ios", "macos"} or {"ios", "macos"}
            line = md.read_text(encoding="utf-8")[:m.start()].count("\n") + 1
            yield f"{md.stem}_{n:02d}_line{line}", plats, m.group(2)


def to_file(name: str, code: str) -> str:
    imports = sorted({ln.strip() for ln in code.splitlines() if ln.startswith("import ")} | {"import SwiftUI"})
    body = "\n".join(ln for ln in code.splitlines() if not ln.startswith("import "))
    body = DECL.sub(lambda m: f"{m.group(1)}fileprivate {m.group(2)}", body)
    return f"// Generated by agent/src/snippet_check.py from {name}. Temporary: delete before committing.\n" \
           + "\n".join(imports) + "\n\n" + body.strip() + "\n"


def write() -> int:
    clean(quiet=True)
    count = {"ios": 0, "macos": 0}
    for name, plats, code in snippets():
        safe = re.sub(r"[^\w]+", "_", name)
        for plat in plats:
            OUT[plat].mkdir(parents=True, exist_ok=True)
            (OUT[plat] / f"_SnippetCheck_{plat}_{safe}.swift").write_text(to_file(name, code), encoding="utf-8")
            count[plat] += 1
    print(f"wrote {count['ios']} iOS and {count['macos']} macOS snippet files")
    return 0


def clean(quiet: bool = False) -> int:
    for path in OUT.values():
        if path.exists():
            shutil.rmtree(path)
    for stray in ROOT.joinpath("SwiftUIForHumans").rglob("_SnippetCheck*.swift"):
        stray.unlink()
    if not quiet:
        print("removed snippet files")
    return 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "write":
        sys.exit(write())
    if cmd == "clean":
        sys.exit(clean())
    if cmd == "list":
        for name, plats, _ in snippets():
            print(f"{name:<60} {','.join(sorted(plats))}")
        sys.exit(0)
    print(__doc__)
    sys.exit(64)
